    <script>
        const DEFAULT_WHATSAPP_NUMBER = '5521976406960';
        const UNIT_WHATSAPP = {
            'Tijuca': '5521967261725',
            'Méier': '5521976406960'
        };

        const $ = (id) => document.getElementById(id);

        function getParam(name) {
            const url = new URL(window.location.href);
            return url.searchParams.get(name) || '';
        }

        function sanitizePhone(value) {
            return (value || '').replace(/\D+/g, '');
        }

        function getWhatsappForUnit(unit) {
            return UNIT_WHATSAPP[unit] || DEFAULT_WHATSAPP_NUMBER;
        }

        function buildMessage(data) {
            const lines = [
                'Olá! Quero garantir a matrícula gratuita e agendar a aula experimental da OBA.',
                '',
                `Criança: ${data.childName} (${data.childAge} anos)`,
                `Responsável: ${data.parentName}`,
                `WhatsApp: ${data.whats}`,
                `Unidade: ${data.unit}`,
                data.restaurant ? `Restaurante parceiro: ${data.restaurant}` : null,
                data.notes ? `Observação: ${data.notes}` : null,
                data.utm ? `UTM: ${data.utm}` : null,
                `Origem: ${data.source}`,
                '',
                'Pode me passar os próximos horários disponíveis?'
            ].filter(Boolean);

            return lines.join('\n');
        }

        function buildWhatsappLink(number, message) {
            return `https://wa.me/${number}?text=${encodeURIComponent(message)}`;
        }

        (function init() {
            const restaurant = getParam('restaurante');
            const unit = getParam('unit');
            const utm = getParam('utm') || getParam('utm_source') || '';

            if (restaurant) {
                $('restaurant').value = restaurant;
                $('restaurantHint').innerHTML = `Detectamos o restaurante parceiro: <strong>${restaurant}</strong>. Complete para reservar sua matrícula gratuita.`;
            }

            if (unit) {
                const options = Array.from($('unit').options).map((opt) => opt.value);
                if (options.includes(unit)) $('unit').value = unit;
            }

            if (utm) $('utm').value = utm;

            const genericMessage = 'Olá! Peguei a folha de colorir no restaurante parceiro e quero informações sobre matrícula gratuita + aula experimental da OBA.';
            $('btnWhatsTop').href = buildWhatsappLink(DEFAULT_WHATSAPP_NUMBER, genericMessage);
        })();

        $('btnCopyMsg').addEventListener('click', async () => {
            const data = {
                childName: $('childName').value.trim() || '[nome da criança]',
                childAge: $('childAge').value.trim() || '[idade]',
                parentName: $('parentName').value.trim() || '[responsável]',
                whats: sanitizePhone($('whats').value) || '[whatsapp]',
                unit: $('unit').value || '[unidade]',
                restaurant: $('restaurant').value.trim(),
                notes: $('notes').value.trim(),
                utm: $('utm').value.trim(),
                source: $('source').value
            };

            const msg = buildMessage(data);
            try {
                await navigator.clipboard.writeText(msg);
                $('btnCopyMsg').textContent = 'Mensagem copiada';
                setTimeout(() => {
                    $('btnCopyMsg').textContent = 'Copiar mensagem';
                }, 1800);
            } catch (error) {
                alert('Não foi possível copiar automaticamente. Copie manualmente:\n\n' + msg);
            }
        });

        $('leadForm').addEventListener('submit', (event) => {
            event.preventDefault();

            const childName = $('childName').value.trim();
            const childAge = $('childAge').value.trim();
            const parentName = $('parentName').value.trim();
            const whats = sanitizePhone($('whats').value);
            const unit = $('unit').value;

            if (!childName || !childAge || !parentName || !whats || !unit) {
                alert('Por favor, preencha os campos obrigatórios.');
                return;
            }

            const restaurantFromUrl = getParam('restaurante');
            const restaurant = (restaurantFromUrl || $('restaurant').value).trim();

            const data = {
                childName,
                childAge,
                parentName,
                whats,
                unit,
                restaurant,
                notes: $('notes').value.trim(),
                utm: $('utm').value.trim(),
                source: $('source').value
            };

            const message = buildMessage(data);
            const whatsappNumber = getWhatsappForUnit(unit);
            const link = buildWhatsappLink(whatsappNumber, message);

            $('btnWhatsFinal').href = link;
            $('successBox').classList.remove('hidden');
            window.open(link, '_blank', 'noopener');
        });
    </script>
